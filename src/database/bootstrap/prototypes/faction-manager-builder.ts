import type { RuntimeObject } from '../../../../types/object';
import type { ObjectManager } from '../../object-manager';
import { registerBuilder, type Builder } from '../builder-registry';

/**
 * Builds the FactionManager singleton
 * Manages faction creation, destruction, memberships, and relationships.
 *
 * Main API:
 *   await $factionManager.create({ name, domain, charGen, description })
 *   await $factionManager.destroy(faction)
 *   await $factionManager.setMembership(entity, faction)
 *   await $factionManager.setRelationship(factionA, factionB, type)
 *
 * The create() method:
 * 1. Creates the faction object via $recycler
 * 2. Allocates port numbers
 * 3. Calls $transports.create(faction) to spin up servers
 * 4. Returns the faction object
 *
 * Memberships:
 * - Entities can belong to one faction at a time
 * - Membership tracked bidirectionally (entity→faction and faction→members)
 *
 * Relationships:
 * - 'friendly', 'hostile', 'neutral' between factions
 * - Bidirectional (stored once with sorted key)
 */
export class FactionManagerBuilder implements Builder {
  static provides = ['factionManager'];
  static depends = ['root'];

  private obj: RuntimeObject | null = null;

  constructor(private manager: ObjectManager) {}

  async build(): Promise<void> {
    const $ = this.manager as any;

    if ($.factionManager) {
      this.obj = $.factionManager;
      return;
    }

    const parentObj = $.root;
    if (!parentObj) throw new Error('FactionManagerBuilder: $root not found');

    this.obj = await this.manager.create({
      parent: parentObj,
      properties: {
          name: 'Faction Manager',
          description:
            'Singleton manager for faction creation, memberships, and relationships.',
          // Map of factionId -> array of member entity IDs
          members: {},
          // Map of entityId -> factionId
          memberships: {},
          // Map of "factionIdA:factionIdB" -> relationship ('friendly', 'hostile', 'neutral')
          relationships: {},
          // Next faction index for port allocation
          nextFactionIndex: 0,
          // Map of domain -> factionId for quick lookup
          domainMap: {},

          abilities: `Singleton manager for the faction system. Accessed via $factionManager.

CREATE/DESTROY: create({name, domain, charGen, description}) creates faction + spins up transports. destroy(faction) shuts down transports + recycles object.

MEMBERSHIP: setMembership(entity, faction) assigns entity to faction (or null to remove). getMembership(entity) returns faction. getMembers(faction) returns entity IDs.

RELATIONSHIPS: setRelationship(factionA, factionB, type) sets relationship (friendly/hostile/neutral). getRelationship(factionA, factionB) returns type.

CHECKS: isFriendly(entityA, entityB) true if same faction or allied. isHostile(entityA, entityB) true if factions hostile.

LOOKUP: getByDomain(domain) returns faction. list() returns all factions.`,
        },
        methods: {},
      });

    const obj = this.obj;

    // Create a new faction (main entry point)
    obj.setMethod(
      'create',
      `
      /** Create a new faction with transport bundle.
       *  @param config - {name, domain, charGen, description, leader?}
       *  @returns The created faction object
       */
      const config = args[0] || {};

      if (!config.name) {
        throw new Error('Faction name is required');
      }

      // Check for duplicate domain
      if (config.domain) {
        const existing = await self.getByDomain(config.domain);
        if (existing) {
          throw new Error('Domain already in use: ' + config.domain);
        }
      }

      // Allocate faction index
      const index = self.nextFactionIndex || 0;
      self.nextFactionIndex = index + 1;

      // Create the faction object
      const faction = await $recycler.create($faction, {
        name: config.name,
        domain: config.domain || null,
        charGen: config.charGen || null,
        description: config.description || '',
        leader: config.leader || null,
        index: index,
        sshHostKey: null, // Will be generated by transport
        ports: null, // Will be set by $transports.create()
      });

      // Register domain mapping
      if (config.domain) {
        const domainMap = self.domainMap || {};
        domainMap[config.domain] = faction.id;
        self.domainMap = domainMap;
      }

      // Spin up transports if $transports is available
      if (typeof $transports !== 'undefined' && $transports.create) {
        await $transports.create(faction);
      }

      return faction;
    `,
    );

    // Destroy a faction
    obj.setMethod(
      'destroy',
      `
      /** Destroy a faction and its transport bundle.
       *  @param faction - The faction object or ID
       *  @param options - {gracefulTimeoutMs?, message?}
       */
      const factionArg = args[0];
      const options = args[1] || {};

      const factionId = typeof factionArg === 'number' ? factionArg : factionArg?.id;
      if (!factionId) {
        throw new Error('Faction is required');
      }

      const faction = await $load(factionId);
      if (!faction) {
        throw new Error('Faction not found: ' + factionId);
      }

      // Shut down transports first
      if (typeof $transports !== 'undefined' && $transports.destroy) {
        await $transports.destroy(faction, options);
      }

      // Remove domain mapping
      if (faction.domain) {
        const domainMap = self.domainMap || {};
        delete domainMap[faction.domain];
        self.domainMap = domainMap;
      }

      // Clear all memberships for this faction
      const memberIds = await self.getMembers(faction);
      for (const memberId of memberIds) {
        await self.setMembership(memberId, null);
      }

      // Recycle the faction object
      await $recycler.recycle(faction);

      return { success: true };
    `,
    );

    // Set entity membership
    obj.setMethod(
      'setMembership',
      `
      /** Set an entity's faction membership.
       *  @param entity - Entity object or ID
       *  @param faction - Faction object, ID, or null to remove
       *  @returns {success, previousFaction?}
       */
      const entityArg = args[0];
      const factionArg = args[1];

      const entityId = typeof entityArg === 'number' ? entityArg : entityArg?.id;
      if (!entityId) {
        return { success: false, error: 'Entity is required' };
      }

      const memberships = self.memberships || {};
      const members = self.members || {};

      // Get previous faction
      const previousFactionId = memberships[entityId];

      // Remove from previous faction
      if (previousFactionId) {
        const prevMembers = members[previousFactionId] || [];
        members[previousFactionId] = prevMembers.filter(id => id !== entityId);
      }

      // Add to new faction
      if (factionArg !== null && factionArg !== undefined) {
        const factionId = typeof factionArg === 'number' ? factionArg : factionArg?.id;
        if (factionId) {
          memberships[entityId] = factionId;
          const factionMembers = members[factionId] || [];
          if (!factionMembers.includes(entityId)) {
            factionMembers.push(entityId);
          }
          members[factionId] = factionMembers;
        }
      } else {
        delete memberships[entityId];
      }

      self.memberships = memberships;
      self.members = members;

      return { success: true, previousFaction: previousFactionId };
    `,
    );

    // Get entity's faction
    obj.setMethod(
      'getMembership',
      `
      /** Get an entity's faction.
       *  @param entity - Entity object or ID
       *  @returns Faction object or null
       */
      const entityArg = args[0];
      const entityId = typeof entityArg === 'number' ? entityArg : entityArg?.id;
      if (!entityId) return null;

      const memberships = self.memberships || {};
      const factionId = memberships[entityId];

      if (!factionId) return null;

      return await $load(factionId);
    `,
    );

    // Get members of a faction
    obj.setMethod(
      'getMembers',
      `
      /** Get all members of a faction.
       *  @param faction - Faction object or ID
       *  @returns Array of entity IDs
       */
      const factionArg = args[0];
      const factionId = typeof factionArg === 'number' ? factionArg : factionArg?.id;
      if (!factionId) return [];

      const members = self.members || {};
      return [...(members[factionId] || [])];
    `,
    );

    // Set relationship between factions
    obj.setMethod(
      'setRelationship',
      `
      /** Set relationship between two factions.
       *  @param factionA - First faction object or ID
       *  @param factionB - Second faction object or ID
       *  @param type - 'friendly', 'hostile', 'neutral'
       *  @returns {success}
       */
      const factionAArg = args[0];
      const factionBArg = args[1];
      const type = args[2];

      const factionAId = typeof factionAArg === 'number' ? factionAArg : factionAArg?.id;
      const factionBId = typeof factionBArg === 'number' ? factionBArg : factionBArg?.id;

      if (!factionAId || !factionBId) {
        return { success: false, error: 'Two factions are required' };
      }

      if (!['friendly', 'hostile', 'neutral'].includes(type)) {
        return { success: false, error: 'Type must be friendly, hostile, or neutral' };
      }

      // Create sorted key for bidirectional lookup
      const key = [factionAId, factionBId].sort((a, b) => a - b).join(':');

      const relationships = self.relationships || {};

      if (type === 'neutral') {
        delete relationships[key];
      } else {
        relationships[key] = type;
      }

      self.relationships = relationships;

      return { success: true };
    `,
    );

    // Get relationship between factions
    obj.setMethod(
      'getRelationship',
      `
      /** Get relationship between two factions.
       *  @param factionA - First faction object or ID
       *  @param factionB - Second faction object or ID
       *  @returns 'friendly', 'hostile', or 'neutral'
       */
      const factionAArg = args[0];
      const factionBArg = args[1];

      const factionAId = typeof factionAArg === 'number' ? factionAArg : factionAArg?.id;
      const factionBId = typeof factionBArg === 'number' ? factionBArg : factionBArg?.id;

      if (!factionAId || !factionBId) return 'neutral';
      if (factionAId === factionBId) return 'friendly'; // Same faction

      const key = [factionAId, factionBId].sort((a, b) => a - b).join(':');
      const relationships = self.relationships || {};

      return relationships[key] || 'neutral';
    `,
    );

    // Check if two entities are friendly
    obj.setMethod(
      'isFriendly',
      `
      /** Check if two entities are friendly.
       *  @param entityA - First entity object or ID
       *  @param entityB - Second entity object or ID
       *  @returns true if same faction or allied factions
       */
      const entityA = args[0];
      const entityB = args[1];

      if (!entityA || !entityB) return false;

      const idA = typeof entityA === 'number' ? entityA : entityA.id;
      const idB = typeof entityB === 'number' ? entityB : entityB.id;

      if (idA === idB) return true; // Same entity

      const factionA = await self.getMembership(idA);
      const factionB = await self.getMembership(idB);

      // No faction = neutral
      if (!factionA || !factionB) return false;

      // Same faction = friendly
      if (factionA.id === factionB.id) return true;

      // Check faction relationship
      const relationship = await self.getRelationship(factionA, factionB);
      return relationship === 'friendly';
    `,
    );

    // Check if two entities are hostile
    obj.setMethod(
      'isHostile',
      `
      /** Check if two entities are hostile.
       *  @param entityA - First entity object or ID
       *  @param entityB - Second entity object or ID
       *  @returns true if factions are hostile
       */
      const entityA = args[0];
      const entityB = args[1];

      if (!entityA || !entityB) return false;

      const idA = typeof entityA === 'number' ? entityA : entityA.id;
      const idB = typeof entityB === 'number' ? entityB : entityB.id;

      if (idA === idB) return false; // Can't be hostile to self

      const factionA = await self.getMembership(idA);
      const factionB = await self.getMembership(idB);

      // No faction = neutral
      if (!factionA || !factionB) return false;

      // Same faction = not hostile
      if (factionA.id === factionB.id) return false;

      // Check faction relationship
      const relationship = await self.getRelationship(factionA, factionB);
      return relationship === 'hostile';
    `,
    );

    // Get faction by domain
    obj.setMethod(
      'getByDomain',
      `
      /** Get faction by domain.
       *  @param domain - Domain string (e.g., 'graycartel.com')
       *  @returns Faction object or null
       */
      const domain = args[0];
      if (!domain) return null;

      const domainMap = self.domainMap || {};
      const factionId = domainMap[domain];

      if (!factionId) return null;

      return await $load(factionId);
    `,
    );

    // List all factions
    obj.setMethod(
      'list',
      `
      /** List all factions.
       *  @returns Array of faction objects
       */
      const domainMap = self.domainMap || {};
      const factionIds = Object.values(domainMap);

      const factions = [];
      for (const factionId of factionIds) {
        const faction = await $load(factionId);
        if (faction) {
          factions.push(faction);
        }
      }

      return factions;
    `,
    );

    // Register a faction that was created externally (for bootstrap)
    obj.setMethod(
      'register',
      `
      /** Register an existing faction object (used during bootstrap).
       *  @param faction - The faction object to register
       *  @returns {success}
       */
      const faction = args[0];
      if (!faction || !faction.id) {
        return { success: false, error: 'Faction object required' };
      }

      // Allocate index if not set
      if (faction.index === null || faction.index === undefined) {
        const index = self.nextFactionIndex || 0;
        faction.index = index;
        self.nextFactionIndex = index + 1;
      } else {
        // Ensure nextFactionIndex is always greater than any registered faction's index
        const currentNext = self.nextFactionIndex || 0;
        if (faction.index >= currentNext) {
          self.nextFactionIndex = faction.index + 1;
        }
      }

      // Register domain mapping
      if (faction.domain) {
        const domainMap = self.domainMap || {};
        domainMap[faction.domain] = faction.id;
        self.domainMap = domainMap;
      }

      return { success: true, index: faction.index };
    `,
    );

    // Get next available faction index
    obj.setMethod(
      'getNextIndex',
      `
      /** Get the next available faction index.
       *  @returns Number for next faction index
       */
      return self.nextFactionIndex || 0;
    `,
    );

    // Property descriptions
    obj.setPropertyDescription(
      'members',
      'Map of factionId -> array of member entity IDs',
    );
    obj.setPropertyDescription(
      'memberships',
      'Map of entityId -> factionId for quick lookup',
    );
    obj.setPropertyDescription(
      'relationships',
      'Map of "factionIdA:factionIdB" -> relationship type (sorted IDs for bidirectional)',
    );
    obj.setPropertyDescription(
      'nextFactionIndex',
      'Counter for allocating faction indices (used for port calculation)',
    );
    obj.setPropertyDescription(
      'domainMap',
      'Map of domain -> factionId for quick domain lookup',
    );
  }

  async registerAliases(): Promise<void> {
    // Register in memory for immediate access
    if (!this.obj) return;
    const objectManager = await this.manager.load(0);
    await objectManager?.call('addAlias', 'factionManager', this.obj.id);
  }
}

// Self-register
registerBuilder(FactionManagerBuilder);
